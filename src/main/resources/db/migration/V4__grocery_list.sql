alter table item add column low_stock_suggested boolean not null default false;

create table grocery_list_item (
    id bigint generated by default as identity primary key,
    user_id bigint not null references app_user (id),
    item_id bigint references item (id) on delete set null,
    item_name varchar(200) not null,
    quantity_needed integer not null,
    source varchar(10) not null check (source in ('AUTO', 'MANUAL')),
    purchased boolean not null default false,
    created_at timestamptz not null default now()
);

create index ix_grocery_user_source on grocery_list_item (user_id, source);
