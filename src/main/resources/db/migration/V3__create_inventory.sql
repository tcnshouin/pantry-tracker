create table location_group (
    id bigint generated by default as identity primary key,
    user_id bigint not null references app_user (id),
    name varchar(120) not null,
    created_at timestamptz not null default now()
);

create unique index ux_location_group_user_name on location_group (user_id, lower(name));

create table item (
    id bigint generated by default as identity primary key,
    user_id bigint not null references app_user (id),
    name varchar(200) not null,
    category_id bigint not null references category (id),
    location_group_id bigint not null references location_group (id),
    low_stock_enabled boolean not null default false,
    low_stock_threshold integer,
    purge_override boolean not null default false,
    empty_since timestamptz,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index ix_item_user_location on item (user_id, location_group_id);
create index ix_item_user_lower_name on item (user_id, lower(name));

create table batch (
    id bigint generated by default as identity primary key,
    item_id bigint not null references item (id) on delete cascade,
    quantity integer not null check (quantity >= 0),
    expiration_date date,
    auto_expiry boolean not null default false,
    purge_override boolean not null default false,
    empty_since timestamptz,
    date_added date not null default current_date
);

create index ix_batch_item_expiration on batch (item_id, expiration_date);
