create table category (
    id bigint generated by default as identity primary key,
    name varchar(120) not null unique
);

create table category_expiry_reference (
    id bigint generated by default as identity primary key,
    category_id bigint not null unique references category (id),
    lower_bound_shelf_life_days integer not null,
    source_note varchar(500) not null
);

insert into category (name) values
    ('Canned goods (vegetables, beans, soup)'),
    ('Pasta, dry'),
    ('Rice, white'),
    ('Cereal, unopened'),
    ('Crackers / biscuits'),
    ('Bread (pantry-stored)'),
    ('Flour, all-purpose'),
    ('Sugar, granulated'),
    ('Cooking oil'),
    ('Peanut butter, unopened'),
    ('Coffee, ground, unopened'),
    ('Dried beans / lentils'),
    ('Spices, ground'),
    ('Instant noodles'),
    ('Condiments / sauces, unopened');

insert into category_expiry_reference (category_id, lower_bound_shelf_life_days, source_note)
select c.id, v.days, 'USDA FoodSafety.gov general pantry shelf-life guidance (lower bound of typical range)'
from category c
join (values
    ('Canned goods (vegetables, beans, soup)', 730),
    ('Pasta, dry', 365),
    ('Rice, white', 730),
    ('Cereal, unopened', 180),
    ('Crackers / biscuits', 60),
    ('Bread (pantry-stored)', 3),
    ('Flour, all-purpose', 180),
    ('Sugar, granulated', 730),
    ('Cooking oil', 365),
    ('Peanut butter, unopened', 180),
    ('Coffee, ground, unopened', 90),
    ('Dried beans / lentils', 365),
    ('Spices, ground', 730),
    ('Instant noodles', 60),
    ('Condiments / sauces, unopened', 365)
) as v (name, days) on v.name = c.name;
